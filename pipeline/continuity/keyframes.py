"""Anchor keyframes generated from references (assets are references, never frames).

For each anchor shot several candidates are rendered from the Shot Bible (talent + product +
location + look + the shot's composition), cleaned, then scored by the vision judge and the face
model. The best candidate is the first frame of the chain; ``keyframe_qc.json`` keeps every
candidate's evidence so the director can overrule the pick.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import List, Optional

import cv2

from pipeline import face_identity
from pipeline.continuity import judge, media
from pipeline.continuity.bible import Shot, ShotBible
from tools.dramaclaw_shot_builder import inpaint_watermark_array

#: image-01 stamps "Generated by MiniMax AI" in the bottom ~5% band; crop a 9:16-preserving margin.
MINIMAX_WATERMARK_BAND = 0.06
#: A keyframe below this judge score is not worth a paid video job.
MIN_KEYFRAME_SCORE = 7.0


def compose_keyframe_prompt(bible: ShotBible, shot: Shot, *, with_reference_roles: bool) -> str:
    roles = ""
    if with_reference_roles:
        roles = (
            "Reference image 1 is the woman: keep her exact face, facial proportions and hair. "
            "Reference image 2 is the product: reproduce this exact bicycle, its shape, colour and lettering. "
            "Do not copy either reference's background or framing.\n"
        )
    return (
        f"{roles}Vertical 9:16 photograph, a single frame from a premium commercial film.\n"
        f"SHOT: {shot.keyframe_prompt}\n"
        f"WOMAN: {bible.talent.canon_text}. Wearing {bible.talent.wardrobe}.\n"
        f"PRODUCT (exact): {bible.product.canon_text}.\n"
        f"LOCATION: {bible.location.canon_text}, {bible.location.time_of_day}, {bible.location.lighting}.\n"
        f"LOOK: {bible.look}. Photoreal, natural skin texture, no text, no logos other than the frame lettering."
    )


def clean_minimax_frame(path: Path) -> None:
    """Crop the watermark band symmetrically so the frame stays 9:16 and carries no stamp."""
    img = cv2.imread(str(path))
    h, w = img.shape[:2]
    band = int(round(h * MINIMAX_WATERMARK_BAND))
    new_h = h - band
    new_w = int(round(new_h * w / h))
    x0 = (w - new_w) // 2
    cv2.imwrite(str(path), img[0:new_h, x0:x0 + new_w])


def _identity(bible: ShotBible, base_dir: Path, image: Path) -> Optional[float]:
    scores = []
    for ref in bible.talent.reference_images:
        try:
            sim = face_identity.identity_similarity(base_dir / ref, image)
        except Exception:  # noqa: BLE001 - face models unavailable must not block the judge
            sim = None
        if sim is not None:
            scores.append(sim)
    return round(max(scores), 4) if scores else None


def generate_anchor(bible: ShotBible, shot: Shot, base_dir: Path, out_dir: Path, *,
                    candidates: int = 3, provider: str = "auto") -> dict:
    """Render, clean and score candidates for one anchor shot; returns the QC record."""
    out_dir.mkdir(parents=True, exist_ok=True)
    talent_refs = [base_dir / r for r in bible.talent.reference_images]
    product_ref = base_dir / bible.product.hero_image
    records: List[dict] = []
    chosen_provider = provider
    for idx in range(candidates):
        path = out_dir / f"{shot.shot_id}_cand{idx + 1}.png"
        record: dict = {"candidate": path.name}
        try:
            if chosen_provider in ("auto", "flow2api"):
                try:
                    media.flow2api_image(compose_keyframe_prompt(bible, shot, with_reference_roles=True), path,
                                         reference_paths=[talent_refs[0], product_ref])
                    record["provider"] = "flow2api"
                    raw = cv2.imread(str(path))
                    cleaned, _ = inpaint_watermark_array(raw)
                    cv2.imwrite(str(path), cleaned)
                except Exception as exc:  # noqa: BLE001
                    if chosen_provider == "flow2api":
                        raise
                    record["flow2api_error"] = str(exc)[:200]
                    chosen_provider = "minimax"  # do not retry a dead gateway for every candidate
            if chosen_provider == "minimax":
                # image-01 on this gateway does not hold a face from a reference (measured SFace
                # 0.03-0.13), so the talent is described in text and identity is locked by the
                # approved keyframe for the rest of the chain.
                media.minimax_image(compose_keyframe_prompt(bible, shot, with_reference_roles=False), path)
                clean_minimax_frame(path)
                record["provider"] = "minimax"
            record["identity_vs_talent_ref"] = _identity(bible, base_dir, path)
            description = media.describe_image(path, judge.DESCRIBE_QUESTION + judge.product_questions(bible))
            record["description"] = description
            record["verdict"] = judge.judge_description(bible, shot, description, frame_role="keyframe")
            record["score"] = record["verdict"]["score"]
        except Exception as exc:  # noqa: BLE001 - one bad candidate must not sink the batch
            record["error"] = str(exc)[:300]
            record["score"] = -1.0
        records.append(record)
        print(f"[keyframe] {shot.shot_id} {path.name}: score={record.get('score')} "
              f"id={record.get('identity_vs_talent_ref')} provider={record.get('provider')}", flush=True)

    best = max(records, key=lambda r: (r["score"], r.get("identity_vs_talent_ref") or 0.0))
    qc = {
        "shot_id": shot.shot_id,
        "candidates": records,
        "selected": best["candidate"] if best["score"] >= 0 else None,
        "selected_score": best["score"],
        "approved": best["score"] >= MIN_KEYFRAME_SCORE,
        "identity_locked_to_reference": best.get("provider") == "flow2api",
        "min_score": MIN_KEYFRAME_SCORE,
    }
    if qc["selected"]:
        selected = out_dir / qc["selected"]
        (out_dir / f"{shot.shot_id}_keyframe.png").write_bytes(selected.read_bytes())
    (out_dir / f"{shot.shot_id}_keyframe_qc.json").write_text(json.dumps(qc, ensure_ascii=False, indent=2), encoding="utf-8")
    return qc
